export const VOICE_REGISTRATION_QUESTION_COUNT = 4

const RECENT_QUESTIONS_KEY_PREFIX = 'voicebank.enrollment.recentQuestions.'

function shuffle<T>(items: T[]): T[] {
  const out = [...items]
  for (let i = out.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[out[i], out[j]] = [out[j], out[i]]
  }
  return out
}

function readRecentQuestionIds(customerId: string | undefined): string[] {
  if (!customerId) return []
  try {
    const raw = localStorage.getItem(RECENT_QUESTIONS_KEY_PREFIX + customerId)
    const parsed: unknown = raw ? JSON.parse(raw) : []
    return Array.isArray(parsed) ? parsed.filter((x): x is string => typeof x === 'string') : []
  } catch {
    return []
  }
}

function writeRecentQuestionIds(customerId: string | undefined, ids: string[]) {
  if (!customerId) return
  try {
    localStorage.setItem(RECENT_QUESTIONS_KEY_PREFIX + customerId, JSON.stringify(ids))
  } catch {
    // Storage unavailable — repeats across enrollments are then possible, never within one.
  }
}

