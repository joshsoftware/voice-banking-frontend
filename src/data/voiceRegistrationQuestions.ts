export function pickRegistrationQuestions(
  count = VOICE_REGISTRATION_QUESTION_COUNT,
  customerId?: string,
): VoiceRegistrationQuestion[] {
  const recent = new Set(readRecentQuestionIds(customerId))
  const fresh = shuffle(VOICE_REGISTRATION_QUESTIONS.filter((q) => !recent.has(q.id)))
  const seen = shuffle(VOICE_REGISTRATION_QUESTIONS.filter((q) => recent.has(q.id)))
  const picked = [...fresh, ...seen].slice(0, Math.min(count, VOICE_REGISTRATION_QUESTIONS.length))
  const history = [...recent, ...picked.map((q) => q.id)].slice(-VOICE_REGISTRATION_QUESTIONS.length)
  writeRecentQuestionIds(customerId, history)
  return picked
}
